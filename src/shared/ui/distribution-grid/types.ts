/** Карточка распределения: картинка элемента и подпись под ней. */
export type TDistributionGridItem = {
  id: string
  imageSrc: string
  title: string
}

/** Колонка распределения: карточка с названием категории сверху и карточки вариантов под ней. */
export type TDistributionGridCategory = {
  id: string
  name: string
  /** id карточек из `elements`, которые лежат в этой колонке (порядок = порядок отрисовки). */
  items: string[]
}

export type TDistributionGridProps = {
  className?: string
  /** Полный список карточек набора; колонки ссылаются на них по id. */
  elements: TDistributionGridItem[]
  /**
   * Колонки слева направо. Компонент рисует не больше 8 — лишние категории
   * отбрасываются (в домене это `primaryMax` для страницы типа `categories`).
   */
  categories: TDistributionGridCategory[]
  /**
   * Заявленный максимум вариантов на одну колонку. Задаёт размер карточки: колонка
   * делится на `elementCount + 1` равных рядов (карточка категории + варианты),
   * поэтому карточка при переносе не меняет размер. Значение зажимается в 1…12.
   *
   * Если вариантов в колонке окажется больше, чем здесь заявлено, ряды добавляются по
   * факту — карточки сжимаются, но ничего не пропадает. Отбрасывается только то, что
   * вышло за `12` (в домене это `secondaryMax` для страницы типа `categories`).
   */
  elementCount: number
  /**
   * id отмеченной карточки; пустая строка — ничего не отмечено. Пока отметка стоит,
   * остальные карточки недоступны для выбора.
   */
  value: string
  /** Отметить карточку. Повторный клик по отмеченной снимает отметку — приходит `''`. */
  onChange: (id: string) => void
  /**
   * Отметить категорию для отмеченной карточки: карточка переезжает в её колонку.
   *
   * Счётчики колонок держит потребитель: в домене они равны (`resizeCategoriesPage`
   * даёт каждой категории одинаковое число вариантов), поэтому перенос делается
   * обменом — вытесненная карточка возвращается в колонку источника. Компонент только
   * сообщает о переносе.
   */
  onAssign?: (elementId: string, categoryId: string) => void
}
